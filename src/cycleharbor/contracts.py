"""Application-facing service ports. Concrete adapters live in infrastructure packages."""
from typing import Protocol
from cycleharbor.domain.models import Bicycle, Ride, FareQuote, PaymentReceipt, RiderMessage, RepairTicket

class BicycleCatalog(Protocol):
    def find(self, bike_id: str) -> Bicycle | None: ...
    def available_at(self, station_id: str) -> list[Bicycle]: ...

class LockGateway(Protocol):
    def unlock(self, bike_id: str) -> bool: ...
    def lock(self, bike_id: str) -> bool: ...

class RideRepository(Protocol):
    def save(self, ride: Ride) -> None: ...
    def find(self, ride_id: str) -> Ride | None: ...

class FarePolicy(Protocol):
    def quote(self, ride: Ride) -> FareQuote: ...

class PaymentGateway(Protocol):
    def capture(self, quote: FareQuote) -> PaymentReceipt: ...

class MessageGateway(Protocol):
    def send(self, message: RiderMessage) -> None: ...

class RepairQueue(Protocol):
    def enqueue(self, ticket: RepairTicket) -> None: ...
